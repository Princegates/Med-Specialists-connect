const { B, req, hmac, adminHdr, ok, done, mk } = require('./lib.js');
const yr = new Date().getUTCFullYear();
const inits = async () => (await fetch('http://127.0.0.1:9001/mock/inits')).json();
const succeed = (ref) => fetch('http://127.0.0.1:9001/mock/succeed/' + encodeURIComponent(ref), { method: 'POST' });
const hook = (obj, sig) => { const raw = JSON.stringify(obj); return req('/api/paystack-webhook', { method: 'POST', raw, headers: { 'x-paystack-signature': sig === undefined ? hmac(raw) : sig } }); };
(async () => {
  console.log('Phase B: prices CONFIRMED');
  let r = await req('/api/config');
  ok('config says prices confirmed', r.j.pricesConfirmed === true, r.j);

  console.log('Automatic invoice for a fixed-fee service');
  r = await req('/api/request', { method: 'POST', body: mk({ phone: '0551000001' }) });
  ok('fixed-fee request returns an invoice link at once', r.status === 200 && r.j.status === 'invoiced' && /^MSC-\d{4}-\d{4}$/.test(r.j.invoice.number) && r.j.invoice.total === 10000 && r.j.invoice.url.startsWith('/invoice?id='), r.j);
  const inv = r.j.invoice;
  r = await req('/api/invoice?id=' + inv.id);
  ok('invoice is payable and not in test mode', r.j.payable === true && r.j.testMode === false && r.j.invoice.status === 'issued', r.j);
  ok('invoice line comes from the price list', r.j.invoice.lines[0].description === 'Specialist appointment coordination' && r.j.invoice.lines[0].amount === 10000, r.j.invoice.lines);
  r = await req('/api/request', { method: 'POST', body: mk({ phone: '0551000002', service: 'Home nursing' }) });
  ok('variable-price service still waits for a quote', r.j.invoice === null && r.j.status === 'awaiting_quote', r.j);

  console.log('Paystack checkout');
  r = await req('/api/pay', { method: 'POST', body: { id: inv.id } });
  ok('pay returns a checkout address', r.status === 200 && r.j.url.startsWith('https://checkout.paystack.com/mock-' + inv.number), r.j);
  const ref1 = r.j.url.split('mock-')[1];
  let i = (await inits())[ref1];
  ok('Paystack was asked for the right amount, currency and invoice', i.amount === 10000 && i.currency === 'GHS' && i.metadata.invoice_id === inv.id, i);
  ok('a placeholder email is used when the patient gave none', /^noreply\+msc-\d{4}-\d{4}@medspecialistconnect\.com$/.test(i.email), i.email);
  r = await req('/api/pay', { method: 'POST', body: { id: 'bad' } });
  ok('pay with a bad id -> 404', r.status === 404, r.status);

  console.log('Signed payment notification');
  const evt = (amount, over = {}) => ({ event: 'charge.success', data: { reference: ref1, amount, currency: 'GHS', channel: 'mobile_money', metadata: { invoice_id: inv.id }, ...over } });
  r = await hook(evt(10000), 'deadbeef');
  ok('wrong signature -> 401', r.status === 401, r.status);
  r = await hook(evt(10000), '');
  ok('missing signature -> 401', r.status === 401, r.status);
  r = await hook(evt(9999));
  ok('correct signature but wrong amount: accepted but NOT marked paid', r.status === 200, r.status);
  r = await req('/api/invoice?id=' + inv.id);
  ok('invoice still unpaid after wrong amount', r.j.invoice.status === 'issued', r.j.invoice.status);
  r = await hook(evt(10000, { currency: 'USD' }));
  r = await req('/api/invoice?id=' + inv.id);
  ok('invoice still unpaid after wrong currency', r.j.invoice.status === 'issued', r.j.invoice.status);
  r = await hook(evt(10000));
  ok('correct signed notification accepted', r.status === 200, r.status);
  r = await req('/api/invoice?id=' + inv.id);
  ok('invoice is now paid, with a paid date', r.j.invoice.status === 'paid' && !!r.j.invoice.paidAt && r.j.payable === false, r.j.invoice);
  r = await hook(evt(10000));
  ok('a repeated notification is harmless', r.status === 200, r.status);
  r = await req('/api/admin/requests', { headers: adminHdr() });
  const row = r.j.requests.find((x) => x.invoice_id === inv.id);
  ok('the request is marked paid too', row.status === 'paid' && row.invoice_status === 'paid', row);
  r = await req('/api/pay', { method: 'POST', body: { id: inv.id } });
  ok('a paid invoice cannot be paid again (409)', r.status === 409, r.status);
  r = await hook({ event: 'charge.success', data: { reference: 'x', amount: 1, currency: 'GHS', metadata: { invoice_id: '00000000-0000-0000-0000-000000000000' } } });
  ok('notification for an unknown invoice is ignored safely', r.status === 200, r.status);
  r = await hook({ event: 'transfer.success', data: {} });
  ok('other event types are ignored safely', r.status === 200, r.status);

  console.log('Return-from-checkout verification');
  r = await req('/api/request', { method: 'POST', body: mk({ phone: '0551000003', email: 'kofi@example.com', service: 'Insurance claims assistance' }) });
  const inv2 = r.j.invoice;
  r = await req('/api/pay', { method: 'POST', body: { id: inv2.id } });
  const ref2 = r.j.url.split('mock-')[1];
  i = (await inits())[ref2];
  ok("the patient's own email is passed to Paystack", i.email === 'kofi@example.com', i.email);
  r = await req('/api/verify', { method: 'POST', body: { id: inv2.id, reference: ref2 } });
  ok('verify before the payment succeeded: still due', r.status === 200 && r.j.status === 'issued', r.j);
  r = await req('/api/verify', { method: 'POST', body: { id: inv2.id, reference: 'OTHER-REF-123456' } });
  ok('verify with a reference from a different invoice -> 404', r.status === 404, r.status);
  r = await req('/api/verify', { method: 'POST', body: { id: inv2.id, reference: '../etc' } });
  ok('verify with a malformed reference -> 400', r.status === 400, r.status);
  await succeed(ref2);
  r = await req('/api/verify', { method: 'POST', body: { id: inv2.id, reference: ref2 } });
  ok('verify after Paystack reports success: paid', r.status === 200 && r.j.status === 'paid', r.j);
  r = await req('/api/invoice?id=' + inv2.id);
  ok('invoice shows paid after verification', r.j.invoice.status === 'paid', r.j.invoice.status);
  done();
})().catch((e) => { console.error('TEST CRASH', e); process.exit(2); });
