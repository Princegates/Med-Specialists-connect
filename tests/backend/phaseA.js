const { B, req, jwt, claims, adminHdr, ok, done, mk } = require('./lib.js');
(async () => {
  console.log('Phase A: prices NOT confirmed');
  let r = await req('/api/config');
  ok('config says billing on, prices not confirmed', r.j.billingEnabled === true && r.j.pricesConfirmed === false, r.j);

  console.log('Request rules');
  r = await req('/api/request', { method: 'POST', body: mk() });
  ok('fixed service stored, NO invoice while prices unconfirmed', r.status === 200 && r.j.invoice === null && r.j.status === 'received', r.j);
  const fixedId = r.j.requestId;
  r = await req('/api/request', { method: 'POST', body: mk({ service: 'Home doctor visit', phone: '0244000222', email: 'ama@example.com' }) });
  ok('quote service goes to awaiting_quote', r.status === 200 && r.j.status === 'awaiting_quote' && r.j.billing === 'quote', r.j);
  const quoteId = r.j.requestId;
  r = await req('/api/request', { method: 'POST', body: mk({ service: 'Medical advice on where to go', phone: '0244000333' }) });
  ok('advice service has no billing', r.status === 200 && r.j.billing === 'none' && r.j.invoice === null, r.j);
  r = await req('/api/request', { method: 'POST', body: mk({ consent: false }) });
  ok('missing consent refused (400)', r.status === 400 && /privacy/i.test(r.j.error), r);
  r = await req('/api/request', { method: 'POST', body: mk({ phone: 'abc' }) });
  ok('bad phone refused (400)', r.status === 400, r);
  r = await req('/api/request', { method: 'POST', body: mk({ service: 'Free money' }) });
  ok('unknown service refused (400)', r.status === 400, r);
  r = await req('/api/request', { method: 'POST', body: mk({ email: 'not-an-email' }) });
  ok('bad email refused (400)', r.status === 400, r);
  r = await req('/api/request', { method: 'POST', raw: '{not json' });
  ok('broken JSON refused (400)', r.status === 400, r);
  r = await req('/api/request', { method: 'POST', body: mk({ botcheck: 'x', name: 'Spam Bot', phone: '0299999999' }) });
  ok('spam trap pretends success', r.status === 200 && r.j.ok === true && !r.j.requestId, r.j);
  const flood = [];
  for (let i = 0; i < 6; i++) flood.push((await req('/api/request', { method: 'POST', body: mk({ phone: '0201112233' }) })).status);
  ok('6th request in an hour from one phone is refused (429)', flood.slice(0, 5).every((s) => s === 200) && flood[5] === 429, flood);

  console.log('Admin sign-in checks');
  r = await req('/api/admin/requests');
  ok('no token -> 401', r.status === 401, r.status);
  r = await req('/api/admin/requests', { headers: { 'Cf-Access-Jwt-Assertion': jwt(claims({ aud: ['other'] })) } });
  ok('wrong audience -> 401', r.status === 401, r.status);
  r = await req('/api/admin/requests', { headers: { 'Cf-Access-Jwt-Assertion': jwt(claims({ exp: Math.floor(Date.now() / 1000) - 10 })) } });
  ok('expired token -> 401', r.status === 401, r.status);
  r = await req('/api/admin/requests', { headers: { 'Cf-Access-Jwt-Assertion': jwt(claims({ email: 'stranger@example.com' })) } });
  ok('email not on the allow-list -> 401', r.status === 401, r.status);
  r = await req('/api/admin/requests', { headers: { 'Cf-Access-Jwt-Assertion': jwt(claims({ iss: 'https://evil.example.com' })) } });
  ok('wrong issuer -> 401', r.status === 401, r.status);
  r = await req('/api/admin/requests', { headers: { 'Cf-Access-Jwt-Assertion': jwt(claims(), { tamper: true }) } });
  ok('tampered signature -> 401', r.status === 401, r.status);
  r = await req('/api/admin/requests', { headers: adminHdr() });
  ok('valid sign-in -> 200 and lists requests (not the spam one)', r.status === 200 && r.j.requests.length >= 8 && !r.j.requests.some((x) => x.name === 'Spam Bot'), r.status);
  ok('admin list includes health note text but no secrets', r.j.requests.every((x) => !('email_hash' in x)));

  console.log('Admin invoice actions');
  r = await req('/api/admin/invoice', { method: 'POST', headers: { 'Cf-Access-Jwt-Assertion': jwt(claims()) }, body: { requestId: quoteId, lines: [{ description: 'x', amountGhs: 10 }] } });
  ok('POST without matching Origin -> 403', r.status === 403, r.status);
  r = await req('/api/admin/invoice', { method: 'POST', headers: adminHdr(), body: { requestId: quoteId, lines: [{ description: 'Coordination fee', amountGhs: 0 }] } });
  ok('zero-amount line refused (400)', r.status === 400, r);
  r = await req('/api/admin/invoice', { method: 'POST', headers: adminHdr(), body: { requestId: quoteId, lines: [] } });
  ok('no lines refused (400)', r.status === 400, r);
  r = await req('/api/admin/invoice', { method: 'POST', headers: adminHdr(), body: { requestId: quoteId, lines: [{ description: 'Coordination fee', amountGhs: 100 }, { description: 'Doctor fee (provider charge)', amountGhs: 350.5 }], note: 'Provider fee is charged by the doctor.' } });
  const yr = new Date().getUTCFullYear();
  ok('quote request gets an invoice MSC-YYYY-0001 with the right total', r.status === 200 && r.j.invoice.number === `MSC-${yr}-0001` && r.j.invoice.total === 45050, r.j);
  const inv1 = r.j.invoice;
  r = await req('/api/admin/invoice', { method: 'POST', headers: adminHdr(), body: { requestId: quoteId, lines: [{ description: 'again', amountGhs: 5 }] } });
  ok('second invoice for the same request refused (409)', r.status === 409, r);
  r = await req('/api/admin/requests', { headers: adminHdr() });
  const row = r.j.requests.find((x) => x.id === quoteId);
  ok('request moved to invoiced', row.status === 'invoiced' && row.invoice_number === inv1.number, row);

  console.log('Public invoice page data');
  r = await req('/api/invoice?id=' + inv1.id);
  ok('invoice readable by its link', r.status === 200 && r.j.invoice.lines.length === 2 && r.j.invoice.billTo === 'Ama Mensah', r.j);
  ok('invoice shows test mode and is not payable', r.j.testMode === true && r.j.payable === false, r.j);
  ok('phone is masked and email/health note are not exposed', r.j.invoice.contact.includes('***') && !JSON.stringify(r.j).includes('ama@example.com') && !JSON.stringify(r.j).includes('0244000222'));
  r = await req('/api/invoice?id=00000000-0000-0000-0000-000000000000');
  ok('unknown invoice -> 404', r.status === 404, r.status);
  r = await req('/api/invoice?id=1');
  ok('malformed id -> 404', r.status === 404, r.status);
  r = await req('/api/pay', { method: 'POST', body: { id: inv1.id } });
  ok('payment refused while prices are unconfirmed (403)', r.status === 403, r);

  console.log('Manual payment, void and re-issue');
  r = await req('/api/admin/invoice-status', { method: 'POST', headers: adminHdr(), body: { invoiceId: inv1.id, status: 'paid', reference: 'MoMo 12345' } });
  ok('staff can mark an invoice paid', r.status === 200, r);
  r = await req('/api/invoice?id=' + inv1.id);
  ok('invoice now shows paid', r.j.invoice.status === 'paid' && !!r.j.invoice.paidAt, r.j.invoice);
  r = await req('/api/admin/invoice-status', { method: 'POST', headers: adminHdr(), body: { invoiceId: inv1.id, status: 'void' } });
  ok('a paid invoice cannot be voided (409)', r.status === 409, r);
  r = await req('/api/admin/invoice', { method: 'POST', headers: adminHdr(), body: { requestId: fixedId, lines: [{ description: 'Specialist appointment coordination', amountGhs: 100 }] } });
  const inv2 = r.j.invoice;
  ok('second invoice numbered ...-0002', inv2.number === `MSC-${yr}-0002`, inv2);
  r = await req('/api/admin/invoice-status', { method: 'POST', headers: adminHdr(), body: { invoiceId: inv2.id, status: 'void' } });
  ok('an unpaid invoice can be voided', r.status === 200, r);
  r = await req('/api/admin/invoice', { method: 'POST', headers: adminHdr(), body: { requestId: fixedId, lines: [{ description: 'Specialist appointment coordination', amountGhs: 120 }] } });
  ok('after a void the request can be invoiced again; the number is not reused (-0003)', r.status === 200 && r.j.invoice.number === `MSC-${yr}-0003`, r.j);
  r = await req('/api/admin/request-status', { method: 'POST', headers: adminHdr(), body: { requestId: fixedId, status: 'scheduled', notes: 'Booked Dr Mensah 5 Dec' } });
  ok('staff can set a request status and note', r.status === 200, r);
  r = await req('/api/admin/request-status', { method: 'POST', headers: adminHdr(), body: { requestId: fixedId, status: 'banana' } });
  ok('unknown status refused (400)', r.status === 400, r);
  r = await req('/api/admin/catalogue', { headers: adminHdr() });
  ok('catalogue lists services and flags', r.status === 200 && r.j.services.length === 11 && r.j.admin === 'boss@example.com', r.j.admin);
  done();
})().catch((e) => { console.error('TEST CRASH', e); process.exit(2); });
